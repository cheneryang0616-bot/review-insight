_SPACE_RE = re.compile(r"\s+")


def apply_noise(text: str) -> str:
    for k, v in NOISE.items():
        text = text.replace(k, v)
    return _SPACE_RE.sub(" ", text)


def aspect_hits(text: str) -> list:
    """命中的方面（锚点词），一个方面只算一次。"""
    return [k for k, (_, anchors, _, _) in ASPECTS.items()
            if any(w in text for w in anchors)]


def negative_hits(text: str) -> list:
    """命中的"负面表述"方面。这才是真正有区分度的那一列。"""
    return [k for k, (_, _, negs, _) in ASPECTS.items()
            if any(w in text for w in negs)]


def aspect_name(key: str) -> str:
    return ASPECTS[key][0]


def aspect_action(key: str) -> str:
    return ASPECTS[key][3]
